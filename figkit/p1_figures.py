def load_trace(idx):
    import h3.api.basic_int as h3i
    from geomark.detect import pair_sets
    from geomark.prf import PRF
    from geomark.scheme import Scheme, seeds_for_cells
    from geomark.hexgrid import parent

    d = pickle.load(open(P1 / "results/gen/gpt_porto_r9_s0/gm_kgw__k0__s0.pkl", "rb"))
    sch = Scheme(**{k: v for k, v in d["meta"]["scheme"].items() if k in Scheme.__dataclass_fields__})
    prf = PRF(0)
    t = d["traces"][idx]
    cells = [int(c) for c in t["cells"]]
    seeds, _ = seeds_for_cells(np.asarray(cells, dtype=np.int64), t["slot"], sch)
    u_path = prf.pairs("fine", seeds, cells)
    green_path = u_path < sch.gamma
    b = sch.bin_of_slot(t["slot"])
    # neighbourhood: all r9 cells within the bbox of the path, padded
    disk = set()
    for c in cells:
        disk.update(h3i.grid_disk(c, 7))
    disk = sorted(disk)
    # seed a step in coarse cell P would use: ((P,), 0, b)  (k=1, coarse context, no mid)
    s_example = seeds[min(len(seeds) - 1, 3)]
    bg_green = {}
    for c in disk:
        P = parent(c, sch.coarse_res)
        s = _seed_for_coarse(s_example, P)
        bg_green[c] = bool(prf.vector("fine", s, [c])[0] < sch.gamma)
    fine, _ = pair_sets(np.asarray(cells, dtype=np.int64), t["slot"], sch)
    return dict(cells=cells, green=green_path, slot=t["slot"], bin=b, disk=disk, bg_green=bg_green,
                coarse={c: parent(c, sch.coarse_res) for c in disk}, n_pairs=len(fine), gamma=sch.gamma,
                seeds=seeds)


def _seed_for_coarse(s_example, P):
    """Replace the coarse history of an example seed by (P,), keeping its structure (mid context, bin)."""
    h, m, b = s_example
    return ((int(P),), m, b)


class Proj:
    def __init__(self, lat0, lon0):
        self.lat0, self.lon0 = lat0, lon0
        self.kx = 111320.0 * np.cos(np.radians(lat0))
        self.ky = 110540.0

    def __call__(self, lat, lon):
        return (np.asarray(lon) - self.lon0) * self.kx, (np.asarray(lat) - self.lat0) * self.ky


def cell_poly(c, proj):
    import h3.api.basic_int as h3i
    b = np.array(h3i.cell_to_boundary(int(c)))
    x, y = proj(b[:, 0], b[:, 1])
    return np.c_[x, y]


def coarse_edges(disk, coarse, proj):
    """Edges of r9 cells whose neighbour across the edge lies in a different coarse cell."""
    import h3.api.basic_int as h3i
    segs = []
    dset = set(disk)
    for c in disk:
        for nb in h3i.grid_ring(c, 1):
            if nb in dset and coarse[nb] != coarse[c] and c < nb:
                e = h3i.cells_to_directed_edge(c, nb)
                bd = np.array(h3i.directed_edge_to_boundary(e))
                x, y = proj(bd[:, 0], bd[:, 1])
                segs.append(np.c_[x, y])
    return segs


def osm_edges(bbox_ll):
    """Road centre-lines inside a lat/lon bbox from the cached Porto drive graph (graphml)."""
    import xml.etree.ElementTree as ET
    path = P1 / "data/osm/porto_drive.graphml"
    ns = {"g": "http://graphml.graphdrawing.org/xmlns"}
    root = ET.parse(path).getroot()
    keys = {k.get("id"): k.get("attr.name") for k in root.findall("g:key", ns)}
    kx = [k for k, v in keys.items() if v == "x"]
    ky = [k for k, v in keys.items() if v == "y"]
    kgeom = [k for k, v in keys.items() if v == "geometry"]
    khw = [k for k, v in keys.items() if v == "highway"]
    g = root.find("g:graph", ns)
    nodes = {}
    for n in g.findall("g:node", ns):
        dd = {d.get("key"): d.text for d in n.findall("g:data", ns)}
        nodes[n.get("id")] = (float(dd[ky[0]]), float(dd[kx[0]]))
    lat0, lat1, lon0, lon1 = bbox_ll
    out = []
    for e in g.findall("g:edge", ns):
        dd = {d.get("key"): d.text for d in e.findall("g:data", ns)}
        if kgeom and dd.get(kgeom[0]):
            txt = dd[kgeom[0]]
            pts = txt[txt.index("(") + 1:txt.rindex(")")].split(",")
            ll = [(float(p.split()[1]), float(p.split()[0])) for p in pts]
        else:
            ll = [nodes[e.get("source")], nodes[e.get("target")]]
        arr = np.array(ll)
        if ((arr[:, 0] > lat0) & (arr[:, 0] < lat1) & (arr[:, 1] > lon0) & (arr[:, 1] < lon1)).any():
            hw = dd.get(khw[0], "") if khw else ""
            out.append((arr, hw))
    return out


# ------------------------------------------------------------------ map panel
def draw_map(ax, T, x0, y0, w, h, show_roads=True):
    """Draw the hex map into the box (x0, y0, w, h) of a points canvas."""
    import h3.api.basic_int as h3i
    from matplotlib.patches import Polygon
    from matplotlib.collections import LineCollection, PolyCollection

    cells = T["cells"]
    lat, lon = zip(*[h3i.cell_to_latlng(c) for c in cells])
    proj = Proj(np.mean(lat), np.mean(lon))
    px, py = proj(np.array(lat), np.array(lon))
    # fit the path (with margin) into the box, preserving aspect
    cx, cy = (px.max() + px.min()) / 2, (py.max() + py.min()) / 2
    span = max((px.max() - px.min()) / (w - 30), (py.max() - py.min()) / (h - 30))
    s = 1.0 / span

    def tr(xy):
        xy = np.atleast_2d(xy)
        return np.c_[x0 + w / 2 + (xy[:, 0] - cx) * s, y0 + h / 2 + (xy[:, 1] - cy) * s]

    clip = K.rbox(ax, x0, y0, w, h, fc="white", ec=tint(C["blue"], 0.35), lw=0.6, r=5, zorder=1.5)
    # roads
    if show_roads:
        latlo, lathi = min(lat) - 0.02, max(lat) + 0.02
        lonlo, lonhi = min(lon) - 0.03, max(lon) + 0.03
        segs, lws = [], []
        for arr, hw in osm_edges((latlo, lathi, lonlo, lonhi)):
            x, y = proj(arr[:, 0], arr[:, 1])
            segs.append(tr(np.c_[x, y]))
            lws.append(0.75 if any(k in hw for k in ("primary", "trunk", "motorway", "secondary")) else 0.35)
        lc = LineCollection(segs, colors=[tint(C["ink2"], 0.22)], linewidths=lws, zorder=2.2, capstyle="round")
        lc.set_clip_path(clip)
        ax.add_collection(lc)
    # hexes
    polys, fcs = [], []
    on_path = set(cells)
    for c in T["disk"]:
        P = cell_poly(c, proj)
        polys.append(tr(P))
        fcs.append(tint(C["aqua"], 0.22) if T["bg_green"][c] else (1, 1, 1, 0.0))
    pc = PolyCollection(polys, facecolors=fcs, edgecolors=[tint(C["ink2"], 0.16)], linewidths=0.3, zorder=2.5)
    pc.set_clip_path(clip)
    ax.add_collection(pc)
    # coarse r7 boundaries
    ce = [tr(sg) for sg in coarse_edges(T["disk"], T["coarse"], proj)]
    lc = LineCollection(ce, colors=[tint(C["violet"], 0.85)], linewidths=1.1, zorder=3.2, capstyle="round")
    lc.set_clip_path(clip)
    ax.add_collection(lc)
    # path cells
    for c, g in zip(cells, T["green"]):
        P = tr(cell_poly(c, proj))
        ax.add_patch(Polygon(P, closed=True, fc=C["aqua"] if g else tint(C["ink2"], 0.30),
                             ec="white", lw=0.5, zorder=3.5))
    # trajectory through centroids
    pts = tr(np.c_[px, py])
    ax.plot(pts[:, 0], pts[:, 1], color=C["ink"], lw=0.9, zorder=4, solid_capstyle="round")
    ax.scatter(pts[:, 0], pts[:, 1], s=3.0, color=C["ink"], zorder=4.1, linewidths=0)
    return pts, s, tr, proj


