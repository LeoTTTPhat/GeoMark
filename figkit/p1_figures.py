    aw = (R - L - wgap) / 2
    axes = [fig.add_axes([L + i * (aw + wgap), B, aw, Tp - B]) for i in range(2)]
    nrow = len(ROWS)
    ypos = np.arange(nrow)[::-1]
    for ai, (ax, ds) in enumerate(zip(axes, DATA)):
        ax.set_xscale("log")
        ax.set_xlim(0.4, 200)
        ax.set_ylim(-0.6, nrow - 0.4)
        ax.axvspan(0.4, 3.0, color=tint(C["ink2"], 0.08), lw=0, zorder=0)
        ax.axvline(3.0, color=C["ink2"], lw=0.7, ls=(0, (2, 1.5)), zorder=1)
        for y in ypos:
            ax.axhline(y, color=C["grid"], lw=0.5, zorder=0.5)
        for name in ["Post-hoc recolor", "Exact-hash KGW", "GeoMark step-neutral", "GeoMark-KGW"]:
            vals = DATA[ds][name]
            st = STYLE[name]
            for y, v in zip(ypos, vals):
                if v is None:
                    continue
                ax.plot([v], [y], linestyle="none", marker=st["marker"], ms=st["ms"], mfc=st["mfc"],
                        mec=st["color"] if st["mfc"] == "white" else "white", mew=0.8 if st["mfc"] == "white" else 0.6,
                        zorder=4 if "GeoMark" in name else 3, clip_on=False)
        # connector from exact-hash to GeoMark-KGW (what coarse seeding buys)
        for y, a, b in zip(ypos, DATA[ds]["Exact-hash KGW"], DATA[ds]["GeoMark-KGW"]):
            if a is not None and b is not None:
                ax.plot([a, b], [y, y], color=tint(C["blue"], 0.45), lw=1.4, zorder=2, solid_capstyle="round")
        ax.set_yticks([])
        ax.set_xticks([1, 3, 10, 30, 100])
        ax.set_xticklabels(["1", "3", "10", "30", "100"])
        ax.xaxis.set_minor_formatter(plt.NullFormatter())
        ax.tick_params(axis="x", pad=1.5)
        for sp in ["top", "right", "left"]:
            ax.spines[sp].set_visible(False)
        ax.set_title(ds, fontsize=7, color=C["ink"], fontweight="bold", pad=3)
        if ai == 0:
            ax.text(2.75, nrow - 0.52, "p > 10$^{-3}$", ha="right", va="center", fontsize=5.4, color=C["ink2"])
    fig.text((L + R) / 2, 0.035, "median $-\\log_{10} p$ of a 100-trace dataset (log scale)", ha="center",
             fontsize=6.3, color=C["ink2"])
    # row labels + icons in the gutter
    gax = fig.add_axes([0, 0, 1, 1], zorder=-1)
    gax.set_axis_off()
    for y, (lab, ics) in zip(ypos, ROWS):
        yf = B + (Tp - B) * (y + 0.6) / nrow
        gax.text(L - 0.012, yf, lab, ha="right", va="center", fontsize=6.0, color=C["ink"])
        for k, ic in enumerate(ics):
            K.icon(gax, ic, 0.03 + k * 0.042, yf, 8.5, C["orange"] if lab != "no attack" else C["ink2"],
                   mode="axes")
    # legend
    handles = []
    for name in ["GeoMark-KGW", "GeoMark step-neutral", "Exact-hash KGW", "Post-hoc recolor"]:
        st = STYLE[name]
        handles.append(Line2D([], [], linestyle="none", marker=st["marker"], ms=st["ms"], mfc=st["mfc"],
                              mec=st["color"] if st["mfc"] == "white" else "white", mew=0.8, label=name))
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, 1.0), ncol=2, fontsize=6.0,
               handletextpad=0.3, columnspacing=1.2, borderaxespad=0.3, labelspacing=0.35)
    K.save(fig, OUT / "fig_launder_art.pdf")


